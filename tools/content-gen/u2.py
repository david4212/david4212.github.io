from collections import defaultdict
BYCAT = defaultdict(list)
for it in BANK: BYCAT[it.cat].append(it)
GEN = [i for i in BANK if i.cat != 'soft']
for it in BANK:
    for b, r in it.bad: assert b != it.ok, it.ok
def tier(lv): return [i for i in GEN if i.lv == lv] or GEN
LV1CATS = {'apos', 'noapos', 'nosoft', 'neverb', 'pre', 'pri', 'zs', 'cs', 'fi', 'fy'}
def pickother(rng, base, k, lv=2):
    cats = list(BYCAT); rng.shuffle(cats); out = []
    for c in cats:
        if c == base.cat or c == 'soft' or (lv == 1 and c not in LV1CATS): continue
        out.append(rng.choice(BYCAT[c]))
        if len(out) == k: break
    return out

def f_right(T, rng, lv):
    a = rng.choice(tier(lv) if lv == 1 else GEN)
    os_ = pickother(rng, a, 3, lv)
    wr = [(o.bad[0][0], f'правильно {o.ok}: {o.bad[0][1]}') for o in os_]
    return T.add(lv, 'Укажіть слово (словосполучення), написане правильно.', a.ok, wr, 'у хибних варіантах помилка зазвичай одна, але різного типу — перевіряй кожен', 'правильне написання: ' + a.ok)
def f_wrong(T, rng, lv):
    a = rng.choice(tier(lv) if lv == 1 else GEN)
    os_ = pickother(rng, a, 3, lv)
    bad, r = a.bad[0]
    return T.add(lv, 'У якому слові (словосполученні) допущено орфографічну помилку?', bad, [(o.ok, 'написано правильно') for o in os_], 'завдання навпаки: шукаємо неправильне написання', f'правильно {a.ok}: {r}')
def f_row_right(T, rng, lv):
    its = rng.sample(GEN, 12)
    good = its[:3]; lines = [(', '.join(i.ok for i in good), None)]
    for k in range(3):
        grp = its[3 + 3 * k: 6 + 3 * k]; bi = rng.randrange(3); b = grp[bi]
        forms = [i.ok for i in grp]; forms[bi] = b.bad[0][0]
        lines.append((', '.join(forms), f'у слові {b.bad[0][0]} помилка — правильно {b.ok}'))
    return T.add(lv, 'У якому рядку всі слова написано правильно?', lines[0][0], lines[1:], 'в одному слові рядка прихована помилка, яку легко проґавити', 'усі три слова написано за нормою')

def f_apos(T, rng, lv):
    mode = rng.random() < 0.5
    A = BYCAT['apos']; N = BYCAT['noapos'] + BYCAT['soft'][:4]
    if mode:
        a = rng.choice(A); ds = rng.sample(N, 3)
        wr = [(d.ok, d.bad[0][1] if d.cat == 'noapos' else 'тут м’якість передає ь, а не апостроф') for d in ds]
        return T.add(lv, 'У якому слові треба писати апостроф?', a.ok, wr, 'на слух [й] чується й там, де апострофа немає', a.bad[0][1])
    a = rng.choice(N); ds = rng.sample(A, 3)
    return T.add(lv, 'У якому слові апостроф писати НЕ треба?', a.ok, [(d.ok, d.bad[0][1]) for d in ds], 'завдання навпаки: шукаємо слово, де апострофа немає', a.bad[0][1] if a.cat == 'noapos' else 'у цьому слові м’якість позначає ь')
def f_soft(T, rng, lv):
    if rng.random() < 0.5:
        a = rng.choice(BYCAT['soft']); ds = rng.sample(BYCAT['nosoft'], 3)
