def draw_scheme(w, numbered=False, show_text=False, fname=None):
    ms = WL[w]['morphs']
    bw, gap = 74, 10
    W_ = max(380, len(ms) * (bw + gap) + 30)
    H_ = 140 if not numbered else 135
    c = Canvas(W_, H_, 'Морфемна схема слова' if not numbered else 'Морфеми слова')
    x0 = (W_ - (len(ms) * (bw + gap) - gap)) / 2
    for i, (t, k) in enumerate(ms):
        x = x0 + i * (bw + gap); y = 50
        fill, st = COL[k]
        if numbered or show_text:
            c.rect(x, y, bw, 40, fill=fill, stroke=st, sw=2, rx=6)
            c.text(x + bw / 2, y + 26, t if t else 'ø', size=18, anchor='middle', bold=True)
            if numbered: c.text(x + bw / 2, y + 66, str(i + 1), size=20, anchor='middle', bold=True, col='#111827')
        else:
            cx = x + bw / 2
            if k == 'p':
                c.path(f'M {x+8} {y+34} L {x+8} {y+10} L {x+bw-8} {y+10}', stroke=st, w=3)
            elif k == 'r':
                c.path(f'M {x+8} {y+34} Q {cx} {y-8} {x+bw-8} {y+34}', stroke=st, w=3)
            elif k == 's':
                c.path(f'M {x+14} {y+34} L {cx} {y+8} L {x+bw-14} {y+34}', stroke=st, w=3)
            elif k == 'e':
                c.rect(x + 14, y + 6, bw - 28, 28, stroke=st, sw=3, fill='none')
                if not t: c.text(cx, y + 26, 'ø', size=16, anchor='middle', col=st)
            elif k == 'c':
                c.circle(cx, y + 20, 12, stroke=st, sw=3)
            c.text(cx, y + 62, NAME[k], size=11, anchor='middle', col='#4b5563')
    if numbered:
        pass
    else:
        c.text(W_ / 2, H_ - 10, 'ø — нульове закінчення', size=11, anchor='middle', col='#6b7280')
    name = fname or f'u4_{tag(w, numbered, show_text)}'
    p = f'{IMGDIR}/{name}.svg'
    open(p, 'w', encoding='utf-8').write(c.svg())
    return f'/img/ukrainian/{name}.svg'

