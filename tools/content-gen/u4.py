def count_wrongs(ks, key, n):
    nc = ks.count('c')
    cand = []
    if key == 's':
        if nc: cand.append((n + nc, 'сполучний голосний помилково зараховано до суфіксів'))
        cand.append((n + 1, 'закінчення помилково зараховано до суфіксів'))
        if n > 0: cand.append((n - 1, 'один із суфіксів не враховано'))
        cand.append((n + 2, 'до суфіксів помилково віднесено ще й закінчення та інші морфеми'))
    elif key == 'r':
        if nc: cand.append((n + nc, 'сполучний голосний помилково зараховано до коренів'))
        if n > 1: cand.append((n - 1, 'один із коренів не враховано: у складному слові їх кілька'))
        cand.append((n + 1, 'суфікс або префікс помилково зараховано до кореня'))
        cand.append((n + 2, 'до коренів помилково віднесено кілька інших морфем'))
    else:
        cand.append((n + 1, 'частину кореня помилково сприйнято як префікс'))
        if n > 0: cand.append((n - 1, 'префікс не враховано'))
        cand.append((n + 2, 'до префіксів помилково віднесено зайві морфеми'))
    out = []; seen = {n}
    for v, r in cand:
        if v < 0 or v in seen: continue
        seen.add(v); out.append((str(v), r))
    return out
