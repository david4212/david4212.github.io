def analyze(word):
    """word може містити ~ перед дж/дз (один звук-африката)"""
    w = word.replace('~', '\x00').lower()
    tokens = []
    i = 0; letters = 0; sounds = 0; extra_iot = 0; double = 0; has_soft = 0; dz = 0; has_shch = 0; has_ie = []
    clean = re.sub('\x00', '', w)
    prev = ''
    chars = []
    i = 0
    while i < len(w):
        c = w[i]
        if c == '\x00':
            dz += 1; chars.append(('DZ', w[i + 1:i + 3])); i += 3; continue
        chars.append(('c', c)); i += 1
    # пройти
    p = None
    for j, (k, c) in enumerate(chars):
        if k == 'DZ':
            letters += 2; sounds += 1; p = 'C'; continue
        if c == "'" or c == '’': p = "'"; continue
        letters += 1
        if c == 'ь': has_soft += 1; p = 'ь'; continue
        if c == 'щ': sounds += 2; has_shch += 1; p = 'C'; continue
        if c in 'яюєї':
            if c == 'ї' or p in (None, 'V', "'", 'ь'):
                sounds += 2; extra_iot += 1; has_ie.append(c)
            else: sounds += 1
            p = 'V'; continue
        if c in VOW: sounds += 1; p = 'V'; continue
        if c in CONS:
            # подовження
            if j > 0 and chars[j - 1][0] == 'c' and chars[j - 1][1] == c: double += 1
            else: sounds += 1
            p = 'C'; continue
        raise ValueError(c)
    syl = sum(1 for c in clean if c in VOW)
    return dict(w=clean, letters=letters, sounds=sounds, syl=syl, iot=extra_iot, double=double, soft=has_soft, dz=dz, shch=has_shch, ie=has_ie)

