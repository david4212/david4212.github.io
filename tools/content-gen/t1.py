def rt(k, b): return f'√{b}' if k == 1 else f'{k}√{b}'

def f_root_sum(T, rng, lv):
    b = rng.choice([2, 3, 5, 6, 7]); u1, v1 = rng.sample([2, 3, 4, 5, 6], 2)
    s1, s2 = u1 * u1 * b, v1 * v1 * b
    sign = rng.choice([1, -1]); co = u1 + sign * v1
    if co <= 0 or co == 1: return False
    ans = rt(co, b)
    op = '+' if sign > 0 else '−'
    wr = [(f'√{s1 + sign * s2}' if s1 + sign * s2 > 0 else f'√{abs(s1 - s2)}', 'корені під знаком суми/різниці об’єднувати не можна'), (rt(u1 + v1 if sign<0 else abs(u1 - v1), b), 'коефіцієнти при коренях додано/віднято навпаки'), (f'{co}√{s1}', 'множник винесено, але підкореневе число залишилось незмінним'), (f'{co * b}', 'корінь помилково прийнято за множник b')]
    return T.add(lv, f'Спростіть: √{s1} {op} √{s2}.', ans, wr, 'винесіть множник з-під знака кореня й додайте подібні доданки: √(k²·b) = k√b',
                 f'√{s1} = {u1}√{b}, √{s2} = {v1}√{b}; {u1} {op} {v1} = {co}, тож {rt(co, b)}')

