NAMES = ['цілих', 'десятих', 'сотих', 'тисячних']
def f_round(T, rng, lv):
    ip = rng.randint(1, 49); fr = [rng.randint(0, 9) for _ in range(4)]
    digits = ''.join(map(str, fr))
    s = f'{ip},{digits}'
    nd = rng.choice([1, 2, 3])
    def rnd(k):
        base = F(ip) + F(int(digits[:k] or '0'), 10 ** k)
        return base + (F(1, 10 ** k) if int(digits[k]) >= 5 else 0), base
    ans, trunc = rnd(nd)
    up = int(digits[nd]) >= 5
    wr = []
    if up: wr.append((trunc, f'цифру {digits[nd]} відкинуто без збільшення останньої збереженої цифри'))
    else: wr.append((trunc + F(1, 10 ** nd), f'збільшено останню цифру, хоча відкинута цифра {digits[nd]} менша за 5'))
    k2 = nd + 1 if nd < 3 else nd - 1
    wr.append((rnd(k2)[0], f'округлено до {NAMES[k2]}, а не до {NAMES[nd]}'))
    k3 = nd - 1
    wr.append((rnd(k3)[0], f'округлено до {NAMES[k3]}, а не до {NAMES[nd]}'))
    wr.append((ans + F(1, 10 ** nd) if up else ans - F(1, 10 ** nd), 'остання цифра змінена на 1 без підстав'))
    return T.add(lv, f'Округліть число {s} до {NAMES[nd]}.', ans, wr,
                 'якщо перша відкинута цифра ≥ 5, останню збережену збільшують на 1; інакше залишають',
                 f'перша відкинута цифра {digits[nd]}' + (' ≥ 5, тому збільшуємо' if up else ' < 5, тому залишаємо') + f': {fmt(ans)}')

def approx(x):
    x = F(x); d = x.denominator
    while d % 2 == 0: d //= 2
    while d % 5 == 0: d //= 5
    return ('= ' if d == 1 else '≈ ') + dc(float(x), 3)

def f_compare_frac(T, rng, lv):
    while True:
        dens = rng.sample([2, 3, 4, 5, 6, 8, 9, 10, 12, 15, 20], 5)
        fr = []
        for d in dens:
            nmr = rng.randint(1, d - 1)
            if math.gcd(nmr, d) == 1: fr.append(F(nmr, d))
        fr = list(dict.fromkeys(fr))
        if len(fr) >= 5 and len({float(x) for x in fr}) == len(fr): break
    fr = fr[:5]; hi = max(fr); lo = min(fr)
    ask = rng.choice(['найбільше', 'найменше']); ans = hi if ask == 'найбільше' else lo
    txt = f'Яке з чисел {", ".join(fmt(x) for x in fr[:4])} чи {fmt(fr[4])} {ask}?' if False else f'Яке з поданих чисел {ask}: {", ".join(fmt(x) for x in sorted(fr, key=lambda z: rng.random()))}?'
    wr = [(x, f'{fmt(x)} {approx(x)}, а {fmt(ans)} {approx(ans)}') for x in fr if x != ans]
    return T.add(lv, txt, ans, wr, 'не порівнюйте дроби за чисельниками або знаменниками окремо — зводьте до десяткових або спільного знаменника',
                 f'{fmt(ans)} {approx(ans)} — {ask} з усіх')

def f_prime(T, rng, lv):
    def isp(k): return k > 1 and all(k % d for d in range(2, int(k ** .5) + 1))
    ps = [p for p in range(11, 100) if isp(p)]
    p = rng.choice(ps)
    comps = []
    while len(comps) < 4:
        c = rng.randint(21, 99)
        if not isp(c) and c not in comps and c % 2 and c % 5: comps.append(c)
    def fac(k): d = next(d for d in range(2, k) if k % d == 0); return f'{k} = {d} · {k // d}'
    return T.add(lv, rng.choice(['Яке з поданих чисел є простим?', 'Серед чисел знайдіть просте.']) + ' ' + ', '.join(map(str, sorted(comps + [p]))) + '.', p,
                 [(c, fac(c) + ', тобто складене') for c in comps],
                 'просте число має рівно два дільники: 1 і саме це число; перевіряйте ділення на 3, 7, 11, 13',
                 f'{p} не ділиться на жодне просте число до {int(p ** .5)}')

def f_digit_div(T, rng, lv):
    d = rng.choice([3, 9, 3, 9, 11])
    a, b = rng.randint(1, 9), rng.randint(1, 9)
    if d == 11:
        pat = f'{a}*{b}'  # цифри на парних/непарних позиціях
        sols = [x for x in range(10) if int(f'{a}{x}{b}') % 11 == 0]
        txt = f'Яку цифру треба записати замість *, щоб число {a}*{b} ділилося на 11?'
        why = lambda x: f'{a}{x}{b}: ' + f'{a}+{b}−{x} = {fmt(a + b - x)}' + ', не кратне 11'
    else:
        sols = [x for x in range(10) if (a + x + b) % d == 0]
        txt = f'Яку цифру треба записати замість *, щоб число {a}*{b} ділилося на {d}?'
        why = lambda x: f'сума цифр {a}+{x}+{b} = {a + x + b} не кратна {d}'
    if len(sols) != 1: return False
    ans = sols[0]
    others = [x for x in range(10) if x != ans]
    return T.add(lv, txt, ans, [(x, why(x)) for x in rng.sample(others, 5)],
                 'ознака подільності: на 3 і 9 — за сумою цифр; на 11 — за різницею сум цифр на парних і непарних місцях',
                 (f'сума цифр {a}+{ans}+{b} = {a + ans + b}, кратна {d}' if d != 11 else f'{a}+{b}−{ans} = {a + b - ans}, кратне 11'))

