    x, y = rng.choice([(10, 20), (20, 10), (25, 20), (20, 25), (30, 10), (50, 20), (40, 25), (15, 20), (10, 30)])
    s = rng.choice(['up_down', 'down_up'])
    if s == 'up_down':
        m = F(100 + x, 100) * F(100 - y, 100); mid_ = p0 * F(100 + x, 100); txt = f'Ціну товару {p0} грн спочатку підвищили на {x}%, а потім нову ціну знизили на {y}%. Якою стала остаточна ціна (грн)?'
