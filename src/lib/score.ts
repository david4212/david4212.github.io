// Бал пробного НМТ за шкалою 100–200.
// УВАГА: офіційні таблиці переведення тестових балів змінюються щороку й різні для предметів,
// тому тут лінійне наближення: 0% → 100, 100% → 200. За потреби змінюй тільки цю функцію.
export function mockScore(percent: number): number {
  return 100 + Math.max(0, Math.min(100, Math.round(percent)));
}
