export function getAtlasLabels(path: string) {
 const key = path.split("/").pop()?.replace(/\.svg$/,"") || "";
 return (HISTORY_ATLAS_LEGENDS[key] || []).map((label, i)=>({number:i+1,label})).filter(item=>item.label);
}
export function getAtlasPeriod(path: string) {
 const name=path.split("/").pop()||"";
 if(/rus/.test(name))return "IX–XIII ст.";
 if(/halych/.test(name))return "XII–XIV ст.";
 if(/vkl/.test(name))return "XIV–XVI ст.";
 if(/h3/.test(name))return "XVI–XVIII ст.";
 if(/h4/.test(name))return "XVIII – поч. XX ст.";
 if(/h5/.test(name))return "1917–1921";
 if(/h6/.test(name))return "1921–1945";
 if(/h7/.test(name))return "1945–1991";
 return "1991–2023";
}
